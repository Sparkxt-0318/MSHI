"""34_tables.py - markdown tables of every reported number, generated from the saved outputs so the
log and summary quote code output rather than hand-copied values.

Usage: python -I audit/34_tables.py
Output: audit/outputs/tables.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mshi_common as C  # noqa: E402

A = C.CONT_ABBR
MODEL_NAME = {"baseline": "training mean", "ols_P": "OLS log P", "ols_TP": "OLS MAT + log P", "xgb": "XGBoost",
              "xgb_fixed": "XGBoost (fixed hyperparameters)", "ols_TPN": "OLS MAT + log P + log NPP",
              "xgb_npp": "XGBoost + NPP"}


def ci(r, k, fmt="{:+.3f}"):
    return f"{fmt.format(r[k])} [{fmt.format(r[k + '_lo'])}, {fmt.format(r[k + '_hi'])}]"


def a1_tables(v):
    res = pd.read_csv(C.OUT / "a1" / f"transfer_{v}.csv")
    out = [f"### A1 transfer matrix, variant `{v}` (all models, all metrics)", "",
           "R2 on log Rs; RMSE, MAE, bias in g C m-2 yr-1 after back-transformation; 95% bootstrap intervals over "
           "test sites (2000 resamples, seed 42); XGBoost = mean of 20 seeds (seed SD of R2 in last column).", "",
           "| Train -> test | n train | n test | Model | R2 | RMSE | MAE | Bias | Spearman | R2 seed SD |",
           "|---|---:|---:|---|---|---|---|---|---|---:|"]
    for _, r in res.iterrows():
        lab = f"{A[r['train']]} -> {A[r['test']]}" if r["kind"] == "transfer" else f"{A[r['train']]} (block CV)"
        out.append(f"| {lab} | {r['n_train']} | {r['n_test']} | {MODEL_NAME[r['model']]} | {ci(r, 'r2')} | "
                   f"{ci(r, 'rmse_g', '{:.0f}')} | {ci(r, 'mae_g', '{:.0f}')} | {ci(r, 'bias_g', '{:+.0f}')} | "
                   f"{ci(r, 'spearman', '{:+.2f}') if np.isfinite(r['spearman']) else 'n/a'} | {r['r2_seed_sd']:.3f} |")
    return out


def main() -> int:
    md = ["# Tables generated by audit/34_tables.py", "", f"Generated {C.now_utc()}.", ""]
    s0 = json.loads((C.OUT / "step0_counts.json").read_text())
    md += ["## Step 0", "", "| Variant | Records | Sites | Share of cells with >1 record |", "|---|---:|---:|---:|"]
    for v, x in s0["variants"].items():
        md.append(f"| {v} | {x['n_records']} | {x['n_sites']} | {x['share_cells_multi_record']:.3f} |")
    md.append("")
    for v in ["strict", "incl_missing"]:
        md += a1_tables(v) + [""]
        p = pd.read_csv(C.OUT / "a1" / f"paired_{v}.csv")
        p = p[p["metric"] == "r2"]
        md += [f"### A1 paired R2 differences, `{v}` (same bootstrap resamples)", "",
               "| Train -> test | Comparison | Difference [95% CI] | Share of resamples where first is better |",
               "|---|---|---|---:|"]
        for _, r in p.iterrows():
            lab = f"{A[r['train']]} -> {A[r['test']]}" if r["kind"] == "transfer" else f"{A[r['train']]} (block CV)"
            md.append(f"| {lab} | {MODEL_NAME[r['model_a']]} minus {MODEL_NAME[r['model_b']]} | "
                      f"{r['diff']:+.3f} [{r['lo']:+.3f}, {r['hi']:+.3f}] | {r['share_boot_a_better']:.2f} |")
        md.append("")
        cov = pd.read_csv(C.OUT / "a1" / f"coverage_{v}.csv")
        rho = json.loads((C.OUT / "a1" / f"coverage_rho_{v}.json").read_text())["spearman_rho_descriptive_no_test"]
        md += [f"### A1 climate coverage vs skill, `{v}` (descriptive; no tests)", "",
               "| Train -> test | MAT & P in training range | in AOA (weighted DI) | mean DI | in AOA (unweighted) | R2 OLS log P | R2 XGBoost |",
               "|---|---:|---:|---:|---:|---:|---:|"]
        for _, r in cov.iterrows():
            md.append(f"| {A[r['train']]} -> {A[r['test']]} | {r['share_TP_in_range']:.2f} | {r['share_in_aoa_weighted']:.2f} | "
                      f"{r['di_weighted_mean']:.2f} | {r['share_in_aoa_unweighted']:.2f} | {r['r2_ols_P']:+.3f} | {r['r2_xgb']:+.3f} |")
        md += ["", "Spearman rho across the 15 pairs (descriptive): " + "; ".join(
            f"{k}: {x:+.2f}" for k, x in rho.items() if k.startswith(("r2_xgb", "r2_ols_P"))), ""]
        mo = pd.read_csv(C.OUT / "a1" / f"modis_{v}.csv")
        mp = pd.read_csv(C.OUT / "a1" / f"modis_paired_{v}.csv")
        run = json.loads((C.OUT / "a1" / f"modis_run_{v}.json").read_text())
        md += [f"### A1 secondary run with MODIS NPP, `{v}`", "",
               f"Sites without an NPP value dropped: {run['dropped_no_npp']} (of which west of 125 W: "
               f"{run['dropped_west_of_125W']}); kept {run['kept']}.", "",
               "| Train -> test | n train | n test | Model | R2 | Spearman |", "|---|---:|---:|---|---|---|"]
        for _, r in mo.iterrows():
            md.append(f"| {A[r['train']]} -> {A[r['test']]} | {r['n_train']} | {r['n_test']} | {MODEL_NAME[r['model']]} | "
                      f"{ci(r, 'r2')} | {ci(r, 'spearman', '{:+.2f}')} |")
        md += ["", "| Train -> test | Comparison | R2 difference [95% CI] |", "|---|---|---|"]
        for _, r in mp.iterrows():
            md.append(f"| {A[r['train']]} -> {A[r['test']]} | {MODEL_NAME[r['model_a']]} minus {MODEL_NAME[r['model_b']]} | "
                      f"{r['diff']:+.3f} [{r['lo']:+.3f}, {r['hi']:+.3f}] |")
        md.append("")
        ts = C.OUT / "a1" / f"tuning_sensitivity_summary_{v}.csv"
        if ts.exists():
            t = pd.read_csv(ts)
            md += [f"### A1 XGBoost transfer R2 across the 10 best tuning configurations, `{v}`", "",
                   "| Train -> test | R2 (selected) | min | median | max | range | CV MSE best / 10th |",
                   "|---|---:|---:|---:|---:|---:|---|"]
            for _, r in t.iterrows():
                md.append(f"| {A[r['train']]} -> {A[r['test']]} | {r['r2_rank1']:+.3f} | {r['r2_min']:+.3f} | "
                          f"{r['r2_median']:+.3f} | {r['r2_max']:+.3f} | {r['r2_range']:.3f} | "
                          f"{r['cv_mse_best']:.4f} / {r['cv_mse_10th']:.4f} |")
            md.append("")
    a2 = json.loads((C.OUT / "a2" / "a2_results.json").read_text())
    for v, R in a2["variants"].items():
        c, n = R["components"], R["nested"]
        md += [f"## A2, variant `{v}`", "",
               f"One-way random effects (cells with >= 2 records: {c['n_cells']} cells, {c['n_records']} records): "
               f"within-cell variance {c['s2_within']:.3f} [{c['s2_within_lo']:.3f}, {c['s2_within_hi']:.3f}], between-cell "
               f"{c['s2_between']:.3f} [{c['s2_between_lo']:.3f}, {c['s2_between_hi']:.3f}], within share "
               f"{c['share_within']:.3f} [{c['share_within_lo']:.3f}, {c['share_within_hi']:.3f}]; REML: "
               f"within {c['reml']['s2_within']:.3f}, between {c['reml']['s2_between']:.3f}.", "",
               f"Nested (cell -> study -> record), moment estimator: s2_rec {n['s2_rec']:.3f} [{n['s2_rec_lo']:.3f}, "
               f"{n['s2_rec_hi']:.3f}], s2_study {n['s2_study']:.3f} [{n['s2_study_lo']:.3f}, {n['s2_study_hi']:.3f}]; "
               f"REML: s2_cell {n['reml_nested'].get('s2_cell', float('nan')):.3f}, s2_study "
               f"{n['reml_nested'].get('s2_study', float('nan')):.3f}, s2_rec {n['reml_nested'].get('s2_rec', float('nan')):.3f}.", "",
               "| Pair type | Half mean sq. difference [95% CI] | Pairs | Cells |", "|---|---|---:|---:|"]
        for r in R["pair_components"]:
            md.append(f"| {r['component']} | {r['half_sq_diff_cellw']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}] | {r['n_pairs']} | {r['n_cells']} |")
        md += ["", "| Group | Pair type | Half mean sq. difference [95% CI] | Pairs | Cells |", "|---|---|---|---:|---:|"]
        for r in R["method_ecosystem"]:
            if r["n_pairs"]:
                md.append(f"| {r['group']} | {r['label']} | {r['half_sq_diff_cellw']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}] | {r['n_pairs']} | {r['n_cells']} |")
        md += ["", "| Scope | Estimator | Sites | Var(site means) | Mean noise | R2 ceiling [95% CI] |", "|---|---|---:|---:|---:|---|"]
        for r in R["bounds"]:
            lo, hi = r.get("lo"), r.get("hi")
            ci_s = f" [{lo:.3f}, {hi:.3f}]" if lo is not None and hi is not None and np.isfinite(lo) and np.isfinite(hi) else ""
            md.append(f"| {r['scope']} | {r['estimator']} | {r['n_sites']} | {r['var_sites']:.3f} | {r['mean_noise_sites']:.3f} | "
                      f"{r['r2max_sites']:.3f}{ci_s} |")
        md += ["", "Semivariogram summary (site level):", "", "| Continent | Sites | Variance | gamma(0-10 km)/var [95% CI] (pairs) | "
               "gamma(0-25 km)/var [95% CI] (pairs) | plateau 400-1600 km | exp. fit nugget/sill (range, km) |",
               "|---|---:|---:|---|---|---:|---|"]
        for cn, s in R["semivariogram"].items():
            f = s["fit_exp_le1600km"]
            md.append(f"| {cn} | {s['n_sites']} | {s['variance']:.3f} | {s['gamma_0_10km_share']:.2f} [{s['gamma_0_10km_share_lo']:.2f}, "
                      f"{s['gamma_0_10km_share_hi']:.2f}] ({s['n_pairs_0_10km']}) | {s['gamma_0_25km_share']:.2f} "
                      f"[{s['gamma_0_25km_share_lo']:.2f}, {s['gamma_0_25km_share_hi']:.2f}] ({s['n_pairs_0_25km']}) | "
                      f"{s['gamma_plateau_400_1600km']:.3f} | {f.get('nugget', float('nan')):.3f}/{f.get('sill', float('nan')):.3f} "
                      f"({f.get('practical_range_km', float('nan')):.0f}) |")
        fr = pd.DataFrame(R.get("fraction_of_bound", []))
        if len(fr):
            fr = fr[fr["model"].isin(["ols_P", "xgb"])]
            md += ["", "| Train -> test | Model | R2 | Ceiling B2 | R2 / ceiling [95% CI from R2 interval] |", "|---|---|---:|---:|---|"]
            for _, r in fr.iterrows():
                lab = f"{A[r['train']]} -> {A[r['test']]}" if r["kind"] == "transfer" else f"{A[r['train']]} (block CV)"
                md.append(f"| {lab} | {MODEL_NAME[r['model']]} | {r['r2']:+.3f} | {r['bound_B2']:.3f} | "
                          f"{r['fraction_of_B2']:+.2f} [{r['fraction_of_B2_lo']:+.2f}, {r['fraction_of_B2_hi']:+.2f}] |")
        md.append("")
    md += ["COSORE multi-chamber check (plot-scale variance of log annual Rs within a site-year): " +
           json.dumps(a2["cosore_port_level"]), ""]
    # A3
    cc = pd.read_csv(C.OUT / "a3" / "class_counts.csv")
    md += ["## A3", "", "| Scope | Class | Confidence | Records | Studies |", "|---|---|---|---:|---:|"]
    for _, r in cc.iterrows():
        md.append(f"| {r['scope']} | {r['mismatch_class']} | {r['confidence']} | {r['n_records']} | {r['n_studies']} |")
    ov = json.loads((C.OUT / "a3" / "overlap_srdb_qc.json").read_text())
    box = json.loads((C.OUT / "a3" / "box_contamination.json").read_text())
    md += ["", "Overlap with SRDB's own checks: " + json.dumps({k: v for k, v in ov.items() if k != "by_class_on_land"}), "",
           "Original rectangles: " + json.dumps({k: v for k, v in box.items() if not k.endswith("listing")}), ""]
    for v in ["strict", "incl_missing"]:
        f = C.OUT / "a3" / f"effect_delta_{v}.csv"
        if not f.exists():
            continue
        d = pd.read_csv(f)
        md += [f"### A3 effect on transfer metrics, `{v}` (change vs flagged records excluded)", "",
               "| Policy | Train -> test | Model | n train / test (excluded) | dR2 | dRMSE | dMAE | dBias | dSpearman |",
               "|---|---|---|---|---:|---:|---:|---:|---:|"]
        for _, r in d.iterrows():
            md.append(f"| {r['policy']} | {A[r['train']]} -> {A[r['test']]} | {MODEL_NAME[r['model']]} | {r['n_train']}/{r['n_test']} "
                      f"({r['n_train_exclude']}/{r['n_test_exclude']}) | {r['d_r2']:+.3f} | {r['d_rmse_g']:+.1f} | "
                      f"{r['d_mae_g']:+.1f} | {r['d_bias_g']:+.1f} | {r['d_spearman']:+.3f} |")
        md.append("")
    (C.OUT / "tables.md").write_text("\n".join(md))
    print(f"wrote {C.OUT / 'tables.md'} ({len(md)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
